export const FOLLOWED_RE = /^following$/i;

// Whatnot's follower lists are sorted ascending by username, so the head of the list is
// dominated by auto-generated / throwaway accounts (e.g. "___________0",
// "00000000000000000000000000_tex"). These are worthless to follow, so skip them.
export function looksAutoGenerated(username) {
  const u = username.toLowerCase();

  // Long leading run of underscores or digits, e.g. "0000000000000accessthegold".
  // Threshold is 6 so real handles that merely start with a year ("2024cards") survive.
  if (/^[_\d]{6,}/.test(u)) return true;

  // Any long run of one repeated character anywhere.
  if (/(.)\1{5,}/.test(u)) return true;

  // Majority of the name is digits/underscores. Only applied to longer names — short
  // real handles ("mj_23", "kj23") are legitimately digit-heavy.
  const junk = (u.match(/[_\d]/g) ?? []).length;
  if (u.length >= 8 && junk / u.length > 0.5) return true;

  // Essentially no letters at all. Kept loose so short real handles ("kj23") survive.
  if ((u.match(/[a-z]/g) ?? []).length < 2) return true;

  return false;
}

