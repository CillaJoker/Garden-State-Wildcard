// Every Whatnot-specific DOM assumption lives here. If Whatnot redesigns,
// this is the only file that should need changing.
//
// Verified live 2026-07-20 (logged out):
//   - Profile page: https://www.whatnot.com/user/<username>  (200 only in a headed browser;
//     headless trips a Cloudflare challenge)
//   - There is NO /user/<username>/followers or /following route — both 404. Each list is a
//     modal opened by a <button> on the profile, e.g. "25K Followers" / "305.4K Following".
//   - A profile-level "Follow" <button> exists for the profile owner.
//   - The modal's internals require a logged-in session to inspect.

export const BASE_URL = 'https://www.whatnot.com';

// Clicking Follow fires this GraphQL mutation. Its response is the ONLY trustworthy
// confirmation: the button itself flips optimistically on click, so a throttled/rejected
// follow still renders as "Following" until the page is reloaded.
//   {"data":{"followUser":{"success":true,"user":{"isFollowing":true}}}}
export const FOLLOW_MUTATION_URL = 'operationName=FollowUser';

export function followMutationSucceeded(json) {
  const r = json?.data?.followUser;
  return r?.success === true && r?.user?.isFollowing === true;
}

